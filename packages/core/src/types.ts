/**
 * 会计内核的六个冻结契约（开发计划 T02 / §⑤ 5.3）。
 *
 * **本文件是编译期的规格书，不是数据结构草稿。**
 * 这里的每个字段都被三方共用：B（import）产出 `Transaction`，C（rules）消费它并产出
 * `RuleHit`，A（journal）把 `RuleHit` 与分录一起写进哈希链，D（web）展示，E（assertions）留痕。
 * 因此改动任一字段都不是「改个类型」，而是同时改 B/C/A/D/E 五条泳道的输入输出。
 *
 * 三条不许商量的规则：
 * 1. **只允许追加，不允许改语义**。B 只能加可选字段；C 只能往 `EventKey` 追加值。
 * 2. **金额只有一种表示**：整数分（`Cents`）。全仓禁止出现「元」的浮点数。
 * 3. **进哈希的字段即不可变字段**。`PostedVoucher` / `JournalLine` / `RuleHit` 的字段增减
 *    等于历史凭证 hash 全部失效，链要迁移，已建的示例账套全部重建。
 *
 * 变更流程见 `docs/decisions/D001-契约冻结.md`：需 A/B/C/D/E 五方签字。
 */

/* ────────────────────────────────────────────────────────────────────────────
 * 0. 基础单位
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 金额的最小单位：**整数分**（1 元 = 100 分）。
 *
 * 为什么是整数分：`2030.00 × 1% == 20.30` 这类价税分离在浮点数上会得到 20.299999…，
 * 四舍五入到分后与 B3（价税分离断言）的判定基准差 1 分，1 分误差会让 B1 借贷平衡
 * 在「本该绿」的月份随机红灯——红灯一旦变成噪音，机检就等于不存在。
 *
 * 改它会坏什么：改成「元」的浮点、字符串 decimal 或 bigint，`totalDebitCents` 的相等比较、
 * `splitInclusive` 的舍入规则、哈希链的序列化格式三处同时要改，且 B1/B3 的探针全部重写。
 *
 * 运行期整数校验（拒绝小数、拒绝 NaN、拒绝超安全整数）随 T05 落在 `core/money.ts`；
 * 本类型只负责「编译期不要出现别的单位」，不做 brand，是为了让规则与报表能直接写字面量。
 */
export type Cents = number;

/**
 * 可作为货币资金核算的科目编码（`Transaction.account` 的值域）。
 *
 * 为什么只有三个：`Transaction` 是「银行流水」的形状，钱只可能落在 1001 库存现金 /
 * 1002 银行存款 / 1012 其他货币资金（支付宝、微信）。把这个值域收窄在这里，
 * 是为了让 B 泳道不可能产出一条「落在应收账款上的银行流水」。
 *
 * 改它会坏什么：放宽成 `string` 后，解析器可以静默把任何科目塞进流水，
 * B4（账面货币资金 == 对账单余额）的分母就变成可被污染的，断言失去意义。
 */
export type MoneyAccountCode = '1001' | '1002' | '1012';

/* ────────────────────────────────────────────────────────────────────────────
 * 1. 输入模型（B 产出 → C 消费）
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 一条银行流水（或等价的一笔记账输入）。B 泳道的唯一产出形状，C 泳道的唯一输入形状。
 *
 * 为什么在这个形状上冻结：它是 B 与 C 之间**唯一的交接面**。字段一改，
 * `import/` 全部解析器与 `rules/` 全部规则同时返工（开发计划 §5.4：B+C 两条泳道同时停 1 天）。
 */
export interface Transaction {
  /**
   * 流水全局唯一键：`sha1(sourceHash + ':' + rowNo)`，**跨文件稳定**。
   * 为什么不用自增 ID：换一台机器、重导同一个文件都必须算出同一个 ID，
   * 否则 T16 的「同一文件重导 0 新增」无法成立。
   * 改它会坏什么：幂等键失效，重导会重复入账（A7 的分母被污染）。
   */
  readonly txnId: string;

  /**
   * `sources/*.csv` 的内容哈希，只用来判「这个文件变没变」。
   * 为什么与 `txnId` 分开：`txnId` 要跨文件稳定（同一行来自哪个文件不重要），
   * `sourceHash` 要区分文件版本（内容变了要提示重导）。
   */
  readonly sourceHash: string;

  /**
   * 原文件行号（1 起）。**所有报错都必须指向它**。
   * 为什么必填：A7 要求「零静默失败」，而一条报错说不出「第几行」就不算可处理；
   * D 泳道的脏数据报错（T38）四要素之一也是行号。
   * 改它会坏什么：解析失败的提示退化为「这个文件有问题」，用户无从修数据。
   */
  readonly rowNo: number;

  /** 交易日，`YYYY-MM-DD`。为什么用字符串不用 Date：时区会让「跨年那一笔」掉到上一年。 */
  readonly date: string;

  /**
   * 资金方向：`IN` 收、`OUT` 付。
   * 为什么方向独立成字段而不带正负号：带符号金额在求和、绝对值、红冲三处各要一次判断，
   * 三处判断只要有一处写反，就会产出「反向记账」，而这种错在试算平衡里是**看不出来**的。
   */
  readonly direction: 'IN' | 'OUT';

  /**
   * 金额，**恒为正数**，方向在 `direction`。
   * 为什么不许为负：负金额会让「方向反 / 金额错」这两类真实错案长得一模一样，
   * 而 A4 要求差异 100% 可解释，无法区分即不可解释。
   */
  readonly amountCents: Cents;

  /**
   * 对账单上的余额（该笔之后的余额）。**缺失必须为 `null`，不许用 0 冒充**。
   * 为什么不能用 0 占位：B4 与 T17（余额连续性）都以「有没有余额列」为前提，
   * 用 0 冒充会让「本文件没有余额列」伪装成「余额归零」，进而报一个假的断点。
   */
  readonly balanceCents: Cents | null;

  /** 对方户名。**与 `counterpartyAccount` 分属两个槽**——BP2 曾把两者挤在一列里静默丢列。 */
  readonly counterparty: string;

  /**
   * 对方账号。可选：部分银行导出会打码或整列缺失。
   * 为什么设成可选而不是空串：空串与「没有这一列」在「待人工确认列映射」时要给不同提示。
   */
  readonly counterpartyAccount?: string;

  /** 摘要 / 用途。原文照录，规则的关键词匹配与「一句人话」都引用它。 */
  readonly summary: string;

  /** 银行流水号：同一文件内可能重复（合并支付），故不参与 `txnId`。 */
  readonly serialNo?: string;

  /**
   * 幂等键：`date|direction|amount|cp|summary`（T16 使用）。
   * 为什么与 `txnId` 并存：`txnId` 保证「同一个文件同一行只入一次」，
   * `fingerprint` 保证「换文件名 / 重新导出后同一笔不重复记账」。
   * 改它的组成会坏什么：新增或删除任一组成部分，「同日同额两笔都保留」与
   * 「换文件名重导 0 新增」这两条验收必有一条反掉——它们是互斥的，改动前先想清楚。
   */
  readonly fingerprint: string;

  /** 这笔钱实际落在哪个货币资金科目（见 `MoneyAccountCode`）。 */
  readonly account: MoneyAccountCode;
}

/* ────────────────────────────────────────────────────────────────────────────
 * 2. 事件值域（C 全权；值域此处冻结，只允许追加）
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 业务事件的封闭值域。C 泳道按它组织 12 类规则模板，A 泳道按它留痕。
 *
 * **只允许追加新值，不允许修改已有值的语义、也不允许删除。**
 * 为什么这条比别处更硬：改语义不会产生任何编译错误——已经写好并校验通过的 YAML
 * 会在下次运行时**静默错配**到另一个科目（开发计划 §5.4 称之为「最贵的失败」）。
 *
 * 追加记录：`E3` 于 2026-11-09 经确认后补入。§5.3 属转录时漏了一项（BP2 源
 * `core/src/types.ts:17` 原文即有 `'E3' // 赊销确认收入`），**这是追加、不是语义变更**，
 * 走的是本文允许的「C 单方追加 + 通知 A/D」路径，不影响 D001 的五方签字约定。
 * 补入后具名事件正好 12 个，与 T20 的「12 类模板」对齐。
 */
export type EventKey =
  | 'E1' // 收客户款（普票）
  | 'E2' // 收客户款（专票）
  | 'E3' // 赊销确认收入（已开票、款未到；借 1122 应收账款）
  | 'E4' // 收回应收
  | 'E5' // 付供应商（已收票）
  | 'E6' // 赊购
  | 'E7' // 付应付
  | 'E8' // 付费用
  | 'E11' // 股东投入
  | 'E12' // 预收 / 确认收入
  | 'E13' // 股东往来
  | 'E16' // 缴税
  | 'E99'; // 未识别

// 为什么 E99 存在、且只能有一个兜底值：
// 「未识别」必须显形进入待处理清单（A7 零静默失败），而两个以上的兜底值会让
// 「为什么没识别」无法归类，未覆盖清单（T29）就失去分子。

/* ────────────────────────────────────────────────────────────────────────────
 * 3. 规则命中（C 产出 → D 展示 / E 留痕）
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 三问的一个问题（钱动了吗 / 交付了吗 / 开票了吗）。
 *
 * 注意：**本类型未在 T02 冻结。** 开发计划 §5.3 只引用了 `Question[]` 而未给定义，
 * 这里给出最小形状以便 `RuleHit` 可编译，语义所有权归 C 泳道（T27 会扩展它）。
 * 因此它是本文件里唯一允许在后续任务中改字段的类型——不需要五方签字，但需要 C 通知 D。
 */
export interface Question {
  /** 稳定标识，用于回填答案与去重（同一事件同类歧义只问一次）。 */
  readonly id: string;
  /** 给零财务知识用户看的问句，必须是业务事实而不是会计动作。 */
  readonly prompt: string;
  /** 可选项。空数组表示自由文本作答。 */
  readonly options: readonly string[];
  /** 用户的回答；未回答时省略（不要用空串表示「没回答」）。 */
  readonly answer?: string;
}

/**
 * 一条依据。
 *
 * **刻意没有「准则条款」这一种。** 判断依据的条文留在规则库里（`rules.yaml` 的 `cite`），
 * 凭证只记「用了哪条规则、哪一版」。反查关系是可推导的：`ruleId + ruleVersion`
 * 唯一确定一份规则文件，规则文件里写着它引用的是哪一条。把条文内联进每张凭证，
 * 等于把同一段文本在几百张凭证里复制几百遍，而它提供的信息量为零。
 *
 * 更实际的理由：专业财务接手后，看科目与摘要就能判断依据；创始人不看条文号，
 * 看的是「一句人话」。条文既救不了前者，也不是后者要的东西。
 */
export type BasisRef =
  /** 用了哪条规则：规则标识 + 规则版本（`ruleVersion` 由 `RuleHit` 携带，这里给文件位置便于 review）。 */
  | { kind: 'RULE'; file: string; line: number }
  /** 来自哪条流水：`txnId` 保证可追到唯一一笔，`rowNo` 保证用户能回原文件核对。 */
  | { kind: 'TXN'; txnId: string; rowNo: number }
  /** 来自哪张发票（勾稽才用得到；无发票也能出包，见 T18）。 */
  | { kind: 'INVOICE'; invoiceNo: string };

/**
 * 一次规则命中的全部留痕。C 产出，随 `PostedVoucher` 一起进哈希。
 *
 * 为什么它要进哈希而不是单独存一张表：A5 要求「草稿能回答来自哪条流水 + 用了哪条规则 +
 * 为什么这个科目」，而「事后补写依据」是最容易发生的事——依据与凭证同哈希，
 * 改依据就等于改凭证，链会立刻断开。
 */
export interface RuleHit {
  /** 规则标识（YAML 里的键）。与 `ruleVersion` 一起进 `ruleSnapshot`。 */
  readonly ruleId: string;

  /**
   * 规则版本。为什么必填：同一 `ruleId` 的科目映射会被真实流水校准推翻（11/28 的返工），
   * 没有版本号就无法回答「这张凭证是按哪一版规则记的」。
   */
  readonly ruleVersion: string;

  /** 命中的事件类别。改它等于改「这笔业务是什么」，属于改语义。 */
  readonly event: EventKey;

  /**
   * 置信度。只有两档：`HIGH` 可直接确认，`LOW` 必须在确认页逐条看过。
   * 为什么不做 0–1 的分数：分数会诱发「0.8 就算通过」的自动放行，
   * 而 MVP 的立场是「拿不准就让人看」。
   */
  readonly confidence: 'HIGH' | 'LOW';

  /**
   * 「我猜的」：所有没有事实依据、由规则默认值填进去的判断都必须落在这里。
   * **空数组 = 没有猜**，非空时 UI 必须显示「我猜的」（T27 验收点）。
   * 改它会坏什么：字段一去掉，猜测就退化成看不见的默认值，A4 的「差异可解释」失效。
   */
  readonly assumed: readonly string[];

  /** 一句人话，≤40 字，给零财务知识用户看。为什么限长：长了就没人读，没人读等于没有解释。 */
  readonly oneLiner: string;

  /**
   * 依据链。**为空即视为失败**（T28 验收点）。
   * 为什么允许空数组而不是强制至少一项：类型层强制常量长度会逼出「凑一个假依据」，
   * 由断言层判定失败更容易被 review 抓住。
   */
  readonly basis: readonly BasisRef[];

  /** 三问，只对 top5 歧义事件问（不让每次确认都变成问卷）。 */
  readonly questions?: readonly Question[];
}

/* ────────────────────────────────────────────────────────────────────────────
 * 4. 落账模型（A 全权 → D/E 只读）
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 一条分录。
 *
 * 注意这里**没有** `voucherId` 之类的反向引用：分录只有形状，位置由所在的
 * `PostedVoucher.lines` 决定。这样红冲时不可能出现「半张凭证指回另一张」。
 */
export interface JournalLine {
  /** 末级科目编码（存在性由 B2 断言校验，编码来源只允许 `accounts.ts`）。 */
  readonly accountCode: string;

  /**
   * 科目名称快照。为什么要冗余存名字：科目表会随版本变化，
   * 而三年前的凭证必须还能被人读懂——名字随凭证冻结，不是随科目表变。
   */
  readonly accountName: string;

  /** 借 / 贷。与 `Transaction.direction` 无关：流入流出是资金方向，借贷是记账方向，两者会交叉。 */
  readonly direction: 'DEBIT' | 'CREDIT';

  /** 分录金额，整数分，恒为正；借贷由 `direction` 表达（理由同 `Transaction.amountCents`）。 */
  readonly amountCents: Cents;

  /**
   * 往来对象（客户 / 供应商 / 股东名）。
   * **1122 应收账款 / 2202 应付账款 必填**，做的是**对象级**校验而不是总账净额校验——
   * BP2 的死因之一就是「1122 净额为 0 但某个客户挂了 5 万」被放行。
   */
  readonly counterparty?: string;

  /** 原始单据号（发票号 / 流水号）。有就填，用于从凭证反查到文件。 */
  readonly docNo?: string;
}

/**
 * 一张已落账的凭证。
 *
 * **刻意没有 `amount` / `accountCode` / `direction` 这类扁平字段。**
 * 这是类型级的防线，不是风格偏好：只要有 `amount`，LLM（或任何生成式调用）就能
 * 跳过借贷直接给凭证赋值，而一张「有总额但没有分录」的凭证在任何试算平衡里都是平的。
 * 金额与科目**只能**存在于 `lines`，合计**只能**存在于 `totalDebitCents` / `totalCreditCents`，
 * 两者是否一致由 B1 断言判定，不由类型自动兜住。
 */
export interface PostedVoucher {
  /** 凭证 ID（落账时生成，一旦写入永不变化；红冲是新凭证，不改旧的）。 */
  readonly voucherId: string;

  /**
   * 会计期间，`YYYY-MM`，**由 `voucherDate` 派生，不许独立赋值**。
   * 为什么必须派生：期间与日期是两个字段时必然出现「12 月的凭证挂在 11 月」这种
   * 无法从数据里看出来的错，而它会让报表整月错位。派生规则只写在落账入口一处。
   * 改它会坏什么：`read(period)` 的分片边界失效，`journal/*.jsonl` 的月分片要全部重切。
   */
  readonly periodId: string;

  /** 凭证号（期间内序号，形如 `记-0001`）。与 `voucherId` 分开：号会按期间重排，ID 不会。 */
  readonly voucherNo: string;

  /** 记账日期 `YYYY-MM-DD`。`periodId` 的唯一来源。 */
  readonly voucherDate: string;

  /**
   * 摘要。**必填且非空；≤40 字。会计翻开凭证第一眼看的就是它。**
   *
   * 2026-11-09 追加（D004，业务字段变更，交付总监代签）。为什么不能事后补：它进哈希，
   * 补一次就等于全部历史凭证 hash 失效，只能断链迁移或写一版兼容序列化 + 双链并存。
   *
   * 为什么它是「事实内容」而不是可选展示字段：没有摘要的借贷两行，看不出这是销售、
   * 借款还是转账 —— 而这三者在试算平衡里都是平的。规则凭证尚可借 `RuleHit.oneLiner`，
   * `MANUAL` / `REVERSE` 凭证连 `RuleHit` 都没有。
   *
   * 为什么不许塞进 `ruleSnapshot`：那里是「落账时生效的规则及版本」，是**配置快照**；
   * 往里写叙述文本会把「我说了什么」伪装成「规则是什么」，且该键无 schema 约束，
   * 任何调用方都能写任何内容。
   *
   * 粒度是**凭证级**，不是分录级（MVP 一张凭证 = 一个经济事件）。
   */
  readonly summary: string;

  /** 分录。为什么是数组而不是「借一条贷一条」：一借多贷（如代扣个税）是常态。 */
  readonly lines: readonly JournalLine[];

  /** 借方合计。为 `Cents` 且独立存字段，是为了让 B1 能对「合计 vs 分录求和」做双向校验。 */
  readonly totalDebitCents: Cents;

  /** 贷方合计。理由同上。 */
  readonly totalCreditCents: Cents;

  /**
   * 凭证来源。`REVERSE` 是红冲（不是删除）。
   * 为什么不让来源可选：来源决定这张凭证能不能被自动重算，缺省会让「人工改过的凭证」
   * 在下一次导入时被规则覆盖掉。
   *
   * 为什么**没有** `'RECON'`（勾稽调整）：2026-11-09 删除（D004 §7.1）。MVP 的勾稽只出
   * 差异清单、不产凭证 —— 留一个既无生产者、又无摘要来源的值，等于给未来一个「看起来支持」
   * 的错觉（BP2 的 `auxRequired` 声明 21 处、只实现 4 处，同一种病换了个位置）。
   * v0.2 真要做勾稽调整凭证，届时连同摘要来源与格式化规则一起加，不要先留口子。
   */
  readonly source: 'IMPORT' | 'MANUAL' | 'REVERSE';

  /** 红冲指向原 `voucherId`。只在 `source === 'REVERSE'` 时出现——红冲是新增一张反向凭证。 */
  readonly reverses?: string;

  /**
   * 规则快照：落账当时的 `ruleId → ruleVersion` 等键值。
   * 为什么要快照而不是查当前规则库：规则会被真实流水校准推翻，
   * 没有快照就无法复现「当时为什么这么记」。
   * 改它的类型会坏什么：它进哈希，值序列化格式一变，全部历史 hash 失效。
   */
  readonly ruleSnapshot: Readonly<Record<string, string>>;

  /**
   * 触发这张凭证的规则命中（含依据链）。随凭证进哈希，理由见 `RuleHit`。
   * 为什么可选：`MANUAL` / `REVERSE` 凭证没有规则命中，给它们编一个假的 `RuleHit`
   * 比留空更坏（假依据会污染 A5 的可解释率统计）。
   */
  readonly hit?: RuleHit;

  /**
   * 链上前一张凭证的 hash。**是落账顺序的前一张，不是日期顺序的前一张。**
   * 为什么强调这点：补录一张上月凭证时，它的 `prevHash` 指向当下最后一张，
   * 而不是上月最后一张；按日期挑 prev 会让补录直接破坏链。
   */
  readonly prevHash: string;

  /** 本张凭证的 hash（覆盖本凭证全部字段 + `prevHash`）。算法与序列化格式随 T04 冻结。 */
  readonly hash: string;
}

/* ────────────────────────────────────────────────────────────────────────────
 * 5. 断言（E 全权）
 * ──────────────────────────────────────────────────────────────────────────── */

/** 五条 BLOCK 级断言的编号。MVP 只有这五条，不沿用 BP2 的 A1–A29（避免交叉引用歧义）。 */
export type BlockId = 'B1' | 'B2' | 'B3' | 'B4' | 'B5';

/**
 * 一条断言的结论。
 *
 * 为什么 `limitation` 是必填而非可选（开发计划 §5.4）：这条字段是「局限随结论输出」的
 * **编译期兑现**。一旦改成可选，交付包就会退化成 BP2 的「绿勾无边界」——
 * 用户看到绿勾，却不知道这个绿勾没查什么。
 */
export interface AssertionResult {
  /** 断言编号，与 `title` 一起构成汇总表的行标识。 */
  readonly id: BlockId;

  /** 断言标题（一句人话）。为什么不用枚举：标题要能被改文案而不改类型。 */
  readonly title: string;

  /** 是否通过。`skipped` 为 true 时本字段**没有意义**，汇总必须分列，不能合并成一个「绿」。 */
  readonly passed: boolean;

  /**
   * 「本次没查」。未结账月份的 B5 滚动校验就属于这一类。
   * 为什么必须有这个字段：把「没查」写成 `passed: true` 是本项目历史上最贵的假绿勾
   * （开发计划 §6.4 第 1 条：未结账月份损益还在 5xxx，滚动等式本来就不成立）。
   */
  readonly skipped?: boolean;

  /** 严重度。MVP 只有 `BLOCK`；`WARN` 走规则层的 `confidence: 'LOW'`，不在这条通道上。 */
  readonly severity: 'BLOCK';

  /** 失败时的说明（给人看的一句话）。通过时省略。 */
  readonly message?: string;

  /**
   * 证据键值（如「账面 X / 对账 Y / 差 Z」）。
   * 为什么是平面 `Record`：交付包要整段输出，嵌套结构会让排版无法固定；
   * 值只允许数字或字符串，杜绝塞一个对象进来当垃圾桶。
   */
  readonly evidence?: Readonly<Record<string, number | string>>;

  /**
   * **这条断言查不出什么**，编译期必填。
   * 写清「查不出什么」而不是「已检查什么」：前者是用户决策的依据，后者只是自我表扬。
   * 改它（变可选 / 给默认值）会坏什么：交付包退化为「绿勾无边界」，
   * 而「局限说明」是本产品唯一的信任护城河。
   */
  readonly limitation: string;
}

/* ────────────────────────────────────────────────────────────────────────────
 * 6. 唯一写入口（A 独占；B/C/D/E 只读）
 * ──────────────────────────────────────────────────────────────────────────── */

/**
 * 链断裂的原因（2026-11-09 由 `journal/chain.ts` **上移**至此，见 D002-D2-2）。
 *
 * 为什么上移：`JournalPort.verify` 要返回它，而 `JournalPort` 在本文件；若仍声明在
 * `journal/chain.ts`，就会形成 types → journal 的反向依赖（types 是零依赖的叶子）。
 * 这两个类型本来就是跨泳道的 DTO（A 产出、D 展示、E 留痕），放在契约文件里才是它们的位置。
 *
 * 七个值分开的理由是**处置方式不同**，不是分类癖：
 * 内容被改查来源、指针错查备份、顺序错查脚本、锚点不符查"末尾是否被删"、
 * 坏行查"哪一行丢了"——合并成一个 `CHAIN_BROKEN` 等于让使用者无从下手。
 */
export type ChainBreakReason =
  /** 重算 hash ≠ 落盘 hash：内容被改过（金额、科目、依据、期间都落在这条）。 */
  | 'HASH_MISMATCH'
  /** `prevHash` 指向的不是落账顺序的前一张：断链、中间一张被删、或凭证被搬到别的分片。 */
  | 'PREV_HASH_MISMATCH'
  /** 内容与指针各自正确，但文件里的先后与链序矛盾：行被对调/插入。 */
  | 'ORDER_MISMATCH'
  /** 分叉：不止一张凭证指向同一个 prevHash。 */
  | 'FORK'
  /** 凭证里有无法规范化序列化的东西（含未登记字段），无法判定真伪。 */
  | 'CANONICALIZE_FAILED'
  /**
   * 链尾与链外锚点 `journal/.head.json` 不符（D002-D2-5）。
   * 为什么不靠链内字段判断：链内无法区分「末尾被删」与「从来没记过」，只能靠锚点。
   */
  | 'HEAD_MISMATCH'
  /** 分片里出现无法解析的行（不是尾部残片）：数据丢了或被手改，不能给绿。 */
  | 'UNPARSEABLE_LINE';

/** journal 异常的种类。每一项都必须显形（A7），不许静默。 */
export type JournalWarningCode =
  /** 末尾半行（写入中断电），已跳过。 */
  | 'TRUNCATED_TAIL'
  /** 完整但解析不出凭证（含修复残片后留下的垃圾行），已跳过。 */
  | 'UNPARSEABLE_LINE'
  /** `periodId` 与所在分片不一致：文件被人工搬过。 */
  | 'SHARD_MISMATCH'
  /** 启动时发现不止一张「链尾」，链已分叉。 */
  | 'CHAIN_TAIL_AMBIGUOUS'
  /**
   * 锚点文件缺失但 journal 非空：此时只能证明「文件内自洽」，
   * 无法判断末尾有没有被删。**这不是错误，是一块必须交出去的盲区。**
   */
  | 'HEAD_MISSING';

/**
 * 一条必须随结论一起交出去的异常。
 *
 * 为什么不合并进 `ok`：`ok` 是布尔，装不下「哪里、第几行、为什么」；
 * 而判断不了位置的异常，在交付包里等于没出现。
 */
export interface JournalWarning {
  readonly code: JournalWarningCode;
  readonly period: string;
  readonly lineNo: number;
  readonly message: string;
}

/**
 * journal 的唯一写入口。**任何人不得绕过它直写 `journal/*.jsonl`。**
 *
 * 为什么用接口而不是函数集合：接口是「只能有一个实现被注入」的约束，
 * 只要还有第二条写路径，「凭证不可变 + 哈希链完整」就只是习惯而不是保证。
 * `append` 的入参刻意 `Omit<PostedVoucher, 'prevHash' | 'hash'>`：
 * **链上的两个字段必须由实现计算，调用方连传都传不进来**——这是防「手工拼 hash」的类型级措施。
 */
export interface JournalPort {
  /**
   * 追加一张凭证。
   * @param period 目标期间 `YYYY-MM`；实现需校验它与 `v.voucherDate` 派生出的期间一致。
   * @param v 除 `prevHash` / `hash` 外的完整凭证。
   * @returns 落账后由实现计算出的链字段，调用方可据此回显与核验。
   */
  append(
    period: string,
    v: Omit<PostedVoucher, 'prevHash' | 'hash'>,
  ): Promise<{ voucherId: string; prevHash: string; hash: string }>;

  /**
   * 按期间流式读取。为什么要按期间分：3 年后 2 万张凭证全量进内存会拖慢启动，
   * 期间就是天然的分片键（`mybook/journal/<period>.jsonl`）。
   */
  read(period: string): AsyncIterable<PostedVoucher>;

  /** 读取全部期间（E 泳道的断言需要全量视角，如跨表滚动）。 */
  readAll(): AsyncIterable<PostedVoucher>;

  /**
   * 校验整条哈希链。
   * @returns `ok: false` 时 `breakAt` 必须精确指出断点的 `voucherId`
   *          ——只说「链断了」无法定位，等于没查。
   *
   * 2026-11-09 追加 `reason` / `warnings`（D002-D2-2，纯加宽，三个字段都不进哈希域）：
   * 只有布尔的话，D 泳道只能显示「链断了」，用户无从判断该去查来源、查备份还是查锚点。
   * `warnings` 为「不改变 ok 但必须打印」的显形通道（如尾部残片、锚点缺失）。
   */
  verify(): Promise<{
    ok: boolean;
    breakAt?: string;
    reason?: ChainBreakReason;
    warnings?: readonly JournalWarning[];
  }>;
}
